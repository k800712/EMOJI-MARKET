-- 1) P2P 마켓플레이스 판매 등록 테이블 생성
CREATE TABLE IF NOT EXISTS public.emoji_market_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emoji_id BIGINT REFERENCES public.emojis(id) ON DELETE CASCADE,
    seller_wallet TEXT REFERENCES public.web3_users(wallet_address) ON DELETE CASCADE,
    price INTEGER NOT NULL CHECK (price > 0),
    status TEXT DEFAULT 'active' NOT NULL, -- 'active', 'sold', 'cancelled'
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2) 거래 내역 로그 테이블 생성
CREATE TABLE IF NOT EXISTS public.emoji_trade_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT REFERENCES public.emoji_market_listings(id) ON DELETE SET NULL,
    emoji_id BIGINT REFERENCES public.emojis(id) ON DELETE CASCADE,
    seller_wallet TEXT NOT NULL,
    buyer_wallet TEXT NOT NULL,
    price INTEGER NOT NULL,
    fee INTEGER NOT NULL, -- 플랫폼 수수료 (5%)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- RLS 활성화 및 권한 설정 (P2P 장터 조회는 public 개방)
ALTER TABLE public.emoji_market_listings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.emoji_trade_history ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow public select emoji_market_listings" ON public.emoji_market_listings
    FOR SELECT TO public USING (true);

CREATE POLICY "Allow service_role full control on listings" ON public.emoji_market_listings
    FOR ALL TO service_role USING (true) WITH CHECK (true);

CREATE POLICY "Allow public select emoji_trade_history" ON public.emoji_trade_history
    FOR SELECT TO public USING (true);

CREATE POLICY "Allow service_role control on history" ON public.emoji_trade_history
    FOR ALL TO service_role USING (true) WITH CHECK (true);


