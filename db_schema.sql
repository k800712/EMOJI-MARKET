-- 1. web3_users 테이블 생성 (Web3 지갑 기반 유저 관리)
CREATE TABLE IF NOT EXISTS public.web3_users (
    wallet_address TEXT PRIMARY KEY,
    nonce TEXT NOT NULL,
    nonce_expires_at TIMESTAMPTZ NOT NULL,
    nickname TEXT DEFAULT 'MCI_User_' || substr(md5(random()::text), 1, 8),
    points INTEGER DEFAULT 3,
    created_at TIMESTAMPTZ DEFAULT now(),
    updated_at TIMESTAMPTZ DEFAULT now(),
    kakao_id TEXT UNIQUE,
    real_name TEXT,
    push_subscription JSONB,
    pending_emoji_notifications INTEGER DEFAULT 0,
    profile_image_url TEXT,
    status TEXT DEFAULT 'active'
);

-- 코멘트 추가
COMMENT ON COLUMN public.web3_users.wallet_address IS '소문자로 표준화된 이더리움/폴리곤 지갑 주소';
COMMENT ON COLUMN public.web3_users.nonce IS '리플레이 공격 방지용 5분 만료 일회성 난스 토큰';
COMMENT ON COLUMN public.web3_users.points IS '이모티콘 생성용 포인트 잔액 (웰컴 3P 지급)';
COMMENT ON COLUMN public.web3_users.kakao_id IS '카카오 소셜 회원 로그인 고유 ID 매핑';
COMMENT ON COLUMN public.web3_users.real_name IS '카카오 본인인증 검증 실제 실명';
COMMENT ON COLUMN public.web3_users.push_subscription IS '웹 푸시 브라우저 고유 키 저장용';
COMMENT ON COLUMN public.web3_users.pending_emoji_notifications IS '미확인 완성 세트 개수';
COMMENT ON COLUMN public.web3_users.profile_image_url IS '카카오 고해상도 프로필 이미지 저장';
COMMENT ON COLUMN public.web3_users.status IS '유저 계정 활성화 상태';

-- 2. emojis 테이블 생성 (이모티콘 파일 메타데이터 및 NFT 소유권 관리)
CREATE TABLE IF NOT EXISTS public.emojis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uuid UUID UNIQUE DEFAULT gen_random_uuid() NOT NULL,
    creator_wallet TEXT REFERENCES public.web3_users(wallet_address) ON DELETE SET NULL,
    owner_wallet TEXT REFERENCES public.web3_users(wallet_address) ON DELETE SET NULL,
    style_type TEXT NOT NULL,
    file_path TEXT NOT NULL,
    is_nft BOOLEAN DEFAULT false,
    nft_token_id TEXT,
    created_at TIMESTAMPTZ DEFAULT now(),
    status TEXT DEFAULT 'completed',
    is_viewed BOOLEAN DEFAULT true
);

-- 기본값 설정: owner_wallet이 명시되지 않으면 creator_wallet과 동일하게 세팅
ALTER TABLE public.emojis ALTER COLUMN owner_wallet SET DEFAULT NULL;

-- 3. preorders 테이블 생성 (희귀 이모티콘 사전 예약 목록)
CREATE TABLE IF NOT EXISTS public.preorders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_address TEXT UNIQUE NOT NULL,
    email TEXT,
    created_at TIMESTAMPTZ DEFAULT now()
);

-- ==========================================
-- 인덱스(Indices) 생성 (조회 속도 및 성능 최적화)
-- ==========================================
CREATE INDEX IF NOT EXISTS idx_emojis_uuid ON public.emojis(uuid);
CREATE INDEX IF NOT EXISTS idx_emojis_owner_wallet ON public.emojis(owner_wallet);

-- ==========================================
-- RLS (Row Level Security) 및 보안 정책 설정
-- ==========================================

-- RLS 활성화
ALTER TABLE public.web3_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.emojis ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.preorders ENABLE ROW LEVEL SECURITY;

-- 1) web3_users RLS Policy
-- 백엔드(Service Role) 외에, 일반 익명 유저는 서명 인증 전 난스 획득을 위해 본인 지갑 레코드를 Select 하거나 Upsert 할 수 있도록 설정
CREATE POLICY "Allow public select web3_users by address" ON public.web3_users
    FOR SELECT TO public USING (true);

CREATE POLICY "Allow public upsert web3_users" ON public.web3_users
    FOR ALL TO public USING (true) WITH CHECK (true);

-- 2) emojis RLS Policy
-- DRM 보안 가이드라인 준수: 모든 파일 생성 및 다운로드는 Next.js API (Service Role)를 통해서만 안전하게 중계되므로
-- public(비인증 익명)에 대한 직접적인 조회를 차단하고 오직 Service Role만 모든 접근 권한 허용
CREATE POLICY "Allow full access for service_role only" ON public.emojis
    FOR ALL TO service_role USING (true) WITH CHECK (true);

-- (폴백용) 클라이언트 직접 쿼리 허용할 경우: 본인이 소유한 이모지만 Select 허용
CREATE POLICY "Allow select if owner matches wallet" ON public.emojis
    FOR SELECT TO public USING (owner_wallet = current_setting('request.headers', true)::json->>'x-wallet-address');

-- 3) preorders RLS Policy
-- 누구나 사전 예약을 신청(Insert)할 수 있으나, 조회는 불가능하게 통제
CREATE POLICY "Allow public insert preorders" ON public.preorders
    FOR INSERT TO public WITH CHECK (true);

CREATE POLICY "Allow service_role full control on preorders" ON public.preorders
    FOR ALL TO service_role USING (true) WITH CHECK (true);


