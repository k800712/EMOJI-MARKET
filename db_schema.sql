-- 5. 추천인(레퍼럴) 보상 포인트 시스템 관련 DDL 마이그레이션
-- ==========================================

-- 1) web3_users 테이블에 추천 코드 및 상태 필드 추가
ALTER TABLE public.web3_users ADD COLUMN IF NOT EXISTS referral_code TEXT UNIQUE;
ALTER TABLE public.web3_users ADD COLUMN IF NOT EXISTS referred_by TEXT REFERENCES public.web3_users(wallet_address);
ALTER TABLE public.web3_users ADD COLUMN IF NOT EXISTS referral_count INTEGER DEFAULT 0;

-- 2) 신규 가입 유저 발생 시 6자리의 고유 대문자 추천 코드를 자동으로 생성하는 DB 트리거 함수
CREATE OR REPLACE FUNCTION generate_unique_referral_code()
RETURNS TRIGGER AS $$
DECLARE
    new_code TEXT;
    done BOOLEAN := FALSE;
BEGIN
    WHILE NOT done LOOP
        -- 대문자와 숫자가 섞인 6자리 랜덤 코드 생성 (예: EMOJ1A, F8D2K9)
        new_code := upper(substring(md5(random()::text) from 1 for 6));
        -- 중복 검증
        IF NOT EXISTS (SELECT 1 FROM public.web3_users WHERE referral_code = new_code) THEN
            done := TRUE;
        END IF;
    END LOOP;
    NEW.referral_code := new_code;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 3) 유저 가입 전 추천 코드 자동 매핑 트리거 생성
CREATE OR REPLACE TRIGGER trigger_generate_referral_code
BEFORE INSERT ON public.web3_users
FOR EACH ROW
WHEN (NEW.referral_code IS NULL)
EXECUTE FUNCTION generate_unique_referral_code();


